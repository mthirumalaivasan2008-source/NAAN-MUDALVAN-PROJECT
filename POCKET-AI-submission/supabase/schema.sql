create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  avatar_url text,
  currency text default 'INR',
  monthly_income numeric default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists transactions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  title text not null,
  category text not null,
  type text check (type in ('income','expense')) not null,
  amount numeric not null check (amount > 0),
  transaction_date date default current_date,
  created_at timestamptz default now()
);

create table if not exists budgets (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  name text not null,
  amount numeric not null check (amount > 0),
  month date not null,
  created_at timestamptz default now()
);

create table if not exists savings_goals (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  name text not null,
  target_amount numeric not null check (target_amount > 0),
  current_amount numeric default 0,
  deadline date,
  created_at timestamptz default now()
);

alter table profiles enable row level security;
alter table transactions enable row level security;
alter table budgets enable row level security;
alter table savings_goals enable row level security;

create policy "profiles own row" on profiles for all using (auth.uid() = id) with check (auth.uid() = id);
create policy "transactions own rows" on transactions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "budgets own rows" on budgets for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "goals own rows" on savings_goals for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
